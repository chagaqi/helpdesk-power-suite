// Builds the FDK app: browser bundles into app/scripts/, serverless bundle into server/server.js.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const browser = { bundle: true, format: 'iife', platform: 'browser', target: ['es2020'], minify: true, legalComments: 'none', absWorkingDir: root, logLevel: 'warning' };
await Promise.all([
  build({ ...browser, entryPoints: ['src/app.ts'], outfile: 'app/scripts/app.bundle.js' }),
  build({ ...browser, entryPoints: ['src/sidebar.ts'], outfile: 'app/scripts/sidebar.bundle.js' }),
  build({ ...browser, entryPoints: ['src/background.ts'], outfile: 'app/scripts/background.bundle.js' }),
]);

// FDK evaluates server.js in a sandbox exposing $request, $db, renderData and expects `exports = {...}`.
const HANDLERS = ['onAppInstallHandler', 'onAppUninstallHandler', 'hpsCall', 'fdPage', 'exportStep'];
await build({
  bundle: true,
  format: 'iife',
  globalName: '__hps',
  platform: 'node',
  target: ['node18'],
  minify: false,
  legalComments: 'none',
  absWorkingDir: root,
  entryPoints: ['src/server/entry.ts'],
  outfile: 'server/server.js',
  banner: { js: '/* Helpdesk Power Suite — FDK serverless bundle (generated by scripts/build.mjs; do not edit) */' },
  footer: { js: `\nexports = {\n${HANDLERS.map((h) => `  ${h}: function (args) { __hps.handlers.${h}(args); }`).join(',\n')}\n};\n` },
  logLevel: 'warning',
});
console.log('shell-freshworks: built app/scripts/*.bundle.js and server/server.js');
